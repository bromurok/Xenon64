struct FontVertex {
    float x, y, z, w;
    float u0, v0;
    float u1, v1;
    unsigned long color;
};

static const int FONT_MAX_VERTS = 8192;
static FontVertex g_fontVerts[FONT_MAX_VERTS];
static int g_fontVertCount = 0;

inline void FontFlush() {
    if (g_fontVertCount == 0 || !g_pd3dDevice) return;
    g_pd3dDevice->DrawPrimitiveUP(D3DPT_TRIANGLELIST, g_fontVertCount / 3, g_fontVerts, sizeof(FontVertex));
    g_fontVertCount = 0;
}

inline void FontAddQuad(float x, float y, float w, float h, unsigned int color) {
    if (g_fontVertCount + 6 > FONT_MAX_VERTS) {
        FontFlush();
    }
    FontVertex v0 = { x,     y,     0.0f, 1.0f, 0,0, 0,0, color };
    FontVertex v1 = { x + w, y,     0.0f, 1.0f, 0,0, 0,0, color };
    FontVertex v2 = { x,     y + h, 0.0f, 1.0f, 0,0, 0,0, color };
    FontVertex v3 = { x + w, y + h, 0.0f, 1.0f, 0,0, 0,0, color };
    g_fontVerts[g_fontVertCount++] = v0;
    g_fontVerts[g_fontVertCount++] = v1;
    g_fontVerts[g_fontVertCount++] = v2;
    g_fontVerts[g_fontVertCount++] = v1;
    g_fontVerts[g_fontVertCount++] = v3;
    g_fontVerts[g_fontVertCount++] = v2;
}

class Font {
public:
    void Begin() {}
    void End() {}

    void DrawTextF(const char* text, int maxWidth, float x, float y) {
        if (!text || !g_pd3dDevice) return;

        g_pd3dDevice->SetVertexDeclaration(g_pVertexDecl);
        g_pd3dDevice->SetVertexShader(g_pVS);
        g_pd3dDevice->SetPixelShader(g_pPS_FB);
        BOOL bFalse[4] = {0,0,0,0};
        g_pd3dDevice->SetPixelShaderConstantB(0, bFalse, 1);
        g_pd3dDevice->SetRenderState(D3DRS_ZENABLE, FALSE);
        g_pd3dDevice->SetRenderState(D3DRS_ZWRITEENABLE, FALSE);
        g_pd3dDevice->SetRenderState(D3DRS_CULLMODE, D3DCULL_NONE);
        g_pd3dDevice->SetRenderState(D3DRS_ALPHABLENDENABLE, FALSE);
        g_pd3dDevice->SetRenderState(D3DRS_ALPHATESTENABLE, FALSE);
        g_pd3dDevice->SetTexture(0, NULL);

        float W = 640.0f;
        float H = 480.0f;
        float ortho[16] = {
            2.0f/W,  0,       0,  -1,
            0,      -2.0f/H,  0,   1,
            0,       0,       1,   0,
            0,       0,       0,   1
        };
        g_pd3dDevice->SetVertexShaderConstantF(0, ortho, 4);

        int len = (int)strlen(text);
        if (maxWidth > 0 && len > maxWidth) len = maxWidth;

        float ps = 1.0f;
        for (int i = 0; i < len; i++) {
            unsigned char c = (unsigned char)text[i];
            if (c < 32 || c > 127) c = 32;
            int idx = c - 32;
            float cx = x + i * 8.0f * ps;
            for (int row = 0; row < 8; row++) {
                unsigned char bits = g_font8x8[idx][row];
                for (int col = 0; col < 8; col++) {
                    if (bits & (0x80 >> col)) {
                        FontAddQuad(cx + col * ps, y + row * ps, ps, ps, 0xFFFFFFFF);
                    }
                }
            }
        }
        FontFlush();
    }
};
